  function describedYears(text) {
    const k={一:1,二:2,三:3,四:4,五:5,六:6,七:7,八:8,九:9};
    let max=0;
    for(const match of text.matchAll(/([0-9０-９一二三四五六七八九十百千]+)年(?:後|間|目|も|続|の時|のち)/g)){
      const characters=match[1].normalize("NFKC");let total=0,digit=0;
      if (/^[0-9]+$/.test(characters)) total=Number(characters);
      else for (const char of characters) {
        if (char==="十" || char==="百" || char==="千") {total+=(digit||1)*({十:10,百:100,千:1000}[char]);digit=0;}
        else digit=/[0-9]/.test(char) ? digit*10+Number(char) : k[char]||0;
      }
      max=Math.max(max,total+digit);
    }
    return Math.min(max,10000);
  }

