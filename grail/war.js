    if (sceneIndex === bond.signatureSite) weight += .16;
    const ticket = random() * (6 + weight);
    const winner = ticket < weight ? entrants[0] : entrants[1+Math.floor(ticket-weight)];
    return { winner, scene: scenes[sceneIndex] };
