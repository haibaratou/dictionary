  function simulateWorld(entrants,bond,battle,random) {
    let remaining = worldPopulation, year = 0, rank = 1, defeats = 0, exitYear = 0;
    let inWar = true, exitPhase = campaigns.at(-1)[0];
    const chosen = entrants[0];
    const archive = [];
    const sceneId = scenes.indexOf(battle.scene);
    const favorableGround = bond.route.terrain.includes(sceneId);
    for (const [i,[phase,low,high]] of campaigns.entries()) {
      const previous = remaining;
      year += 1 + Math.floor(random()*(i<3 ? 4 : 5));
      remaining = i===campaigns.length-1 ? 1 : Math.max(campaigns.length-i+1,Math.floor(previous*(low+(high-low)*random())));
      archive.push({phase,year,remaining});
      if (!inWar) continue;
      const wave = 1 + i;
      const field = random();
      let takedowns = Math.floor(-Math.log(1-Math.min(field,.999999))*wave*(.9+random()*3.2));
      if (i>1 && random() < .045*wave) {
        const group = Math.min(previous-remaining, Math.floor(6**wave*(.03+random()*.22)));
        takedowns += Math.floor(group*(.1+random()*.9));
      }
      defeats += Math.min(previous-remaining,takedowns);
      // The chronicle follows a protagonist. Seven sampled key actors do not
      // reduce the global population; its successive surviving ranks are real ranges.
      const advance = .61 + (bond.synergy ? .075 : 0) + (favorableGround ? .035 : 0)
        + (bond.owner ? .025 : 0) + (battle.winner===chosen ? .055 : 0)
        + (sceneId===bond.signatureSite ? .025 : 0);
      if (random() >= advance) {
        inWar = false;
        rank = remaining + 1 + Math.floor(random()*(previous-remaining));
        exitPhase = phase;
        exitYear = year;
      }
    }
    const champion = rank===1 ? chosen : battle.winner!==chosen ? battle.winner : pick(entrants.slice(1),random);
    let status;
    if (rank!==1 && random() < ((bond.key==="ward" || bond.key==="heal") ? .13 : .22)) status="戦死";
    else status = random() < .33 ? "引退" : "生存";
    const killer = status==="戦死" ? (rank===2 ? champion : pick(entrants.slice(1),random)) : null;
    return {
      champion,killer,stats:{
        population:worldPopulation,rank,defeats:Math.min(defeats,worldPopulation-rank),lifeYears:0,
        status,killerName:killer?.name || null,exitYear:exitYear || year,warYears:year,phase:exitPhase,aliveHistory:archive
      }
    };
  }

