    const edges=state.map.districts.find(d=>d.id===state.location)?.edges;
    if(!edges?.length)return null;
    const area=edges[hash(state.seed+'/'+day+'/'+state.location)%edges.length];
    const side=(hash('edition/'+state.seed)%2+Math.floor(day/2))%2;
